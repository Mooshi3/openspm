"""OpenSPM content patches: exact single-instruction recipes (state/openspm-code-patches.json).

Applied to the player-local codegen DOL before DolRecomp, so the recompiled module
has them; the backend applies the same list to the boot image in guest RAM
(include/openspm/code_patches.h). A patch whose expected word is not at its
address is a hard error: the build fails closed instead of guessing.
"""

from __future__ import annotations

import json
import struct
from pathlib import Path

MANIFEST = Path(__file__).resolve().parents[2] / "state" / "openspm-code-patches.json"


def load(path: Path = MANIFEST) -> list[dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("schema_version") != 1 or data.get("game_id") != "R8PE01":
        raise RuntimeError(f"{path}: unsupported code patch manifest")
    patches = []
    seen = set()
    for entry in data["patches"]:
        address = int(entry["address"], 16)
        expected = int(entry["expected"], 16)
        replacement = int(entry["replacement"], 16)
        if address & 3 or address in seen or not 0x80003100 <= address < 0x81800000:
            raise RuntimeError(f"code patch {entry['name']}: bad or duplicate address")
        seen.add(address)
        patches.append(
            {
                "name": entry["name"],
                "address": address,
                "expected": expected,
                "replacement": replacement,
                "boot": bool(entry.get("boot", True)),
            }
        )
    return patches


def load_relocations(path: Path = MANIFEST) -> list[dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    out = []
    for entry in data.get("relocations", []):
        src, size, dst = (int(entry[k], 16) for k in ("from", "size", "to"))
        if not (0x80000000 <= src and src + size <= 0x81800000) or not (0x90000000 <= dst and dst + size <= 0x94000000):
            raise RuntimeError(f"relocation {entry['name']}: range outside MEM1 -> MEM2")
        out.append(
            {
                "name": entry["name"],
                "from": src,
                "size": size,
                "to": dst,
                "relf_references": int(entry.get("relf_references", 0)),
                "row_size": int(entry.get("row_size", "0"), 16),
                "rows": int(entry.get("rows", 0)),
            }
        )
        r = out[-1]
        if r["rows"] and (not r["row_size"] or r["size"] % r["row_size"] or
                          r["to"] + r["row_size"] * r["rows"] > 0x94000000 or r["rows"] * r["row_size"] < r["size"]):
            raise RuntimeError(f"relocation {r['name']}: bad rows")
    return out


def relf_character_id_patches(path: Path = MANIFEST) -> int:
    return int(json.loads(path.read_text(encoding="utf-8")).get("relf_character_id_patches", 0))


HEADER = MANIFEST.parents[1] / "include" / "openspm" / "code_patches_table.inc"


def header_text() -> str:
    lines = [
        "/* Generated by tools/native_bridge/openspm_code_patches.py --write-header from",
        "   state/openspm-code-patches.json. Do not edit. */",
        "static const openspm_code_patch k_openspm_code_patches[] = {",
    ]
    for p in load():
        lines.append(
            f'    {{"{p["name"]}", UINT32_C(0x{p["address"]:08X}), UINT32_C(0x{p["expected"]:08X}), '
            f'UINT32_C(0x{p["replacement"]:08X}), {1 if p["boot"] else 0}}},'
        )
    lines.append("};")
    lines.append("static const openspm_code_relocation k_openspm_code_relocations[] = {")
    for r in load_relocations():
        lines.append(
            f'    {{"{r["name"]}", UINT32_C(0x{r["from"]:08X}), UINT32_C(0x{r["size"]:X}), UINT32_C(0x{r["to"]:08X}), '
            f'UINT32_C(0x{r["row_size"]:X}), {r["rows"]}u}},'
        )
    lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    import sys

    if sys.argv[1:] == ["--write-header"]:
        HEADER.write_text(header_text(), encoding="utf-8")
        print(f"wrote {HEADER}")
    else:
        print("usage: openspm_code_patches.py --write-header")


def _dol_offset(dol: bytes | bytearray, address: int) -> int | None:
    offsets = struct.unpack(">18I", dol[0:72])
    addresses = struct.unpack(">18I", dol[72:144])
    sizes = struct.unpack(">18I", dol[144:216])
    for offset, start, size in zip(offsets, addresses, sizes):
        if size and start <= address and address + 4 <= start + size:
            return offset + (address - start)
    return None


def apply(dol: bytes | bytearray, patches: list[dict] | None = None) -> tuple[bytes, list[str]]:
    """Returns the patched DOL and the names applied. Already-patched words are
    accepted (idempotent); anything else is an error."""
    image = bytearray(dol)
    applied = []
    for patch in load() if patches is None else patches:
        offset = _dol_offset(image, patch["address"])
        if offset is None:
            raise RuntimeError(f"code patch {patch['name']}: 0x{patch['address']:08X} is not in the DOL")
        (word,) = struct.unpack_from(">I", image, offset)
        if word == patch["replacement"]:
            applied.append(patch["name"])
            continue
        if word != patch["expected"]:
            raise RuntimeError(
                f"code patch {patch['name']}: expected 0x{patch['expected']:08X} at "
                f"0x{patch['address']:08X}, found 0x{word:08X} (not R8PE01 rev 2?)"
            )
        struct.pack_into(">I", image, offset, patch["replacement"])
        applied.append(patch["name"])
    if patches is None:
        applied += _apply_relf_relocations(image)
        applied += _apply_relf_character_ids(image)
    return bytes(image), applied


RELF_START = 0x80C00000


def _apply_relf_relocations(image: bytearray) -> list[str]:
    """relF code is placed by the build (augment_dol), so its references to a
    relocated table are found here in the player's own codegen DOL, with the
    same checks as tools/content/table_refs.py, and must number exactly
    relf_references."""
    sys_path = str(Path(__file__).resolve().parents[1] / "content")
    import sys as _sys

    if sys_path not in _sys.path:
        _sys.path.insert(0, sys_path)
    import table_refs  # noqa: E402

    names = []
    sections = [s for s in table_refs.parse_dol(bytes(image)) if s.text and s.address >= RELF_START]
    for reloc in load_relocations():
        want = reloc["relf_references"]
        if not want:
            continue
        found = table_refs.find(sections, reloc["from"], reloc["size"])
        if not found["patches"] and not found["problems"]:
            done = table_refs.find(sections, reloc["to"], reloc["size"])
            if len(done["patches"]) == want and not done["problems"]:
                names += [f"{reloc['name']}-relf-{n:02d}" for n in range(want)]
                continue  # already relocated
        if found["problems"] or found["data_pointers"] or len(found["patches"]) != want:
            raise RuntimeError(
                f"relocation {reloc['name']}: relF has {len(found['patches'])} clean references "
                f"(expected {want}), {len(found['problems'])} unsafe ones; not R8PE01 rev 2?"
            )
        delta_hi = ((reloc["to"] - reloc["from"]) >> 16) & 0xFFFF
        for n, ref in enumerate(sorted(found["patches"], key=lambda p: p["address"])):
            offset = _dol_offset(image, ref["address"])
            (word,) = struct.unpack_from(">I", image, offset)
            new_hi = (ref["hi"] + delta_hi) & 0xFFFF
            if word == ref["expected"]:
                struct.pack_into(">I", image, offset, (word & 0xFFFF0000) | new_hi)
            names.append(f"{reloc['name']}-relf-{n:02d}")
    return names


def _apply_relf_character_ids(image: bytearray) -> list[str]:
    """relF's character-id patches (tools/content/character_ids.py,
    docs/CHARACTER-IDS.md), found in the player's own codegen DOL with the
    same analysis as main.dol's; they must number exactly
    relf_character_id_patches."""
    want = relf_character_id_patches()
    if not want:
        return []
    sys_path = str(Path(__file__).resolve().parents[1] / "content")
    import sys as _sys

    if sys_path not in _sys.path:
        _sys.path.insert(0, sys_path)
    import character_ids  # noqa: E402
    import table_refs  # noqa: E402

    found = character_ids.relf_patches(table_refs.parse_dol(bytes(image)))
    if len(found) != want:
        raise RuntimeError(f"character ids: relF has {len(found)} sites to patch (expected {want}); not R8PE01 rev 2?")
    names = []
    for patch in found:
        offset = _dol_offset(image, patch["address"])
        (word,) = struct.unpack_from(">I", image, offset)
        if word not in (patch["expected"], patch["replacement"]):
            raise RuntimeError(f"{patch['name']}: unexpected word 0x{word:08X} at 0x{patch['address']:08X}")
        struct.pack_into(">I", image, offset, patch["replacement"])
        names.append(patch["name"])
    return names
