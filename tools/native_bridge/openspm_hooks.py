"""OpenSPM hook registry (state/openspm-hooks.json, docs/HOOKS.md).

Entries with ``enabled: true`` become host targets in the native module:
``direct_calls.load_host_targets()`` adds them (so every build step that routes
host targets, including both LLVM host-first sets, sees them), the bridge's
dispatcher lists them in ``openspm_hook_targets.inc`` and the backend's hook
table is ``include/openspm/hooks_table.inc``. Both files are generated here
(``--write``) and kept in sync by ``test_openspm_hooks.py``. With no entry
enabled both are empty and the build is unchanged.
"""

from __future__ import annotations

import argparse
import json
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "state" / "openspm-hooks.json"
BRIDGE_INC = Path(__file__).resolve().with_name("openspm_hook_targets.inc")
BACKEND_INC = ROOT / "include" / "openspm" / "hooks_table.inc"
# OPENSPM_HOOK_RETURN_ADDRESS in include/openspm/hooks.h (test_openspm_hooks.py
# checks they agree): below the game's first code at 0x80003100.
RETURN_ADDRESS = 0x80002FF0
NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,47}$")


def load(path: Path = MANIFEST, enabled_only: bool = False) -> list[dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("schema_version") != 1 or data.get("game_id") != "R8PE01" or data.get("revision") != 2:
        raise RuntimeError(f"{path}: unsupported hook registry")
    out, names, addresses = [], set(), set()
    for entry in data["hooks"]:
        name = entry["name"]
        address = int(entry["address"], 16)
        expect = int(entry["expect"], 16)
        if not NAME_RE.match(name) or name in names:
            raise RuntimeError(f"hook {name!r}: bad or duplicate name")
        if address & 3 or address in addresses or not 0x80003100 <= address < 0x81800000:
            raise RuntimeError(f"hook {name}: bad or duplicate address")
        if not 0 <= expect <= 0xFFFFFFFF:
            raise RuntimeError(f"hook {name}: bad expect word")
        names.add(name)
        addresses.add(address)
        enabled = entry.get("enabled") is True
        if enabled_only and not enabled:
            continue
        out.append({"name": name, "address": address, "expect": expect, "enabled": enabled})
    return out


def enabled_addresses(path: Path = MANIFEST) -> set[int]:
    return {hook["address"] for hook in load(path, enabled_only=True)}


def bridge_inc_text(path: Path = MANIFEST) -> str:
    lines = [
        "/* Generated by tools/native_bridge/openspm_hooks.py from state/openspm-hooks.json:",
        "   the enabled hooks, host targets like m14_host_targets.inc (the bridge includes",
        "   both inside its host-target X-macro). Empty = no hook in this build. */",
    ]
    hooks = load(path, True)
    lines += [f"OPENSPM_M14_HOST_TARGET(0x{h['address']:08X}u) /* {h['name']} */" for h in hooks]
    if hooks:
        # Post callbacks: hooked bodies return here (never code; include/openspm/hooks.h).
        lines.append(f"OPENSPM_M14_HOST_TARGET(0x{RETURN_ADDRESS:08X}u) /* OPENSPM_HOOK_RETURN_ADDRESS */")
    return "\n".join(lines) + "\n"


def backend_inc_text(path: Path = MANIFEST) -> str:
    hooks = load(path, True)
    lines = [
        "/* Generated by tools/native_bridge/openspm_hooks.py from state/openspm-hooks.json:",
        "   the enabled hooks for include/openspm/hooks.h (address, name, first instruction). */",
        f"#define OPENSPM_HOOK_TABLE_COUNT {len(hooks)}u",
        "static const openspm_hook_entry k_openspm_hook_table[OPENSPM_HOOK_TABLE_COUNT + 1u] = {",
    ]
    lines += [f"    {{UINT32_C(0x{h['address']:08X}), \"{h['name']}\", UINT32_C(0x{h['expect']:08X})}}," for h in hooks]
    lines += ["    {0u, \"\", 0u}, /* end (keeps the array non-empty) */", "};"]
    return "\n".join(lines) + "\n"


def check_dol(dol: bytes, path: Path = MANIFEST) -> list[str]:
    """Problems with the registry against a main.dol image (all entries, enabled or not)."""
    offsets = struct.unpack(">18I", dol[0:72])
    addresses = struct.unpack(">18I", dol[72:144])
    sizes = struct.unpack(">18I", dol[144:216])
    problems = []
    for hook in load(path):
        word = None
        for off, base, size in zip(offsets, addresses, sizes):
            if size and base <= hook["address"] < base + size:
                word = struct.unpack(">I", dol[off + hook["address"] - base: off + hook["address"] - base + 4])[0]
        if word is None:
            problems.append(f"{hook['name']}: 0x{hook['address']:08X} is not in the DOL")
        elif word != hook["expect"]:
            problems.append(f"{hook['name']}: expected 0x{hook['expect']:08X}, found 0x{word:08X}")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="regenerate the two .inc files")
    parser.add_argument("--check-dol", type=Path, help="check every entry's first instruction in a main.dol")
    args = parser.parse_args()
    if args.write:
        BRIDGE_INC.write_text(bridge_inc_text(), encoding="utf-8", newline="\n")
        BACKEND_INC.write_text(backend_inc_text(), encoding="utf-8", newline="\n")
    if args.check_dol:
        problems = check_dol(args.check_dol.read_bytes())
        for problem in problems:
            print(problem)
        if problems:
            return 1
    hooks = load()
    print(f"OpenSPM hooks: {sum(h['enabled'] for h in hooks)} enabled of {len(hooks)} in the registry")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
